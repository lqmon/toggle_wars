// flagkit codegen: the Flagsmith project as code.
//   - typed flag names (a typo is a compile error in TS, an editor warning in JS)
//   - the variants of each multivariate flag as a union type
//   - FLAG_DEFAULTS: every flag's state in one environment (Production by default), so the app still
//     behaves sanely when Flagsmith is slow or unreachable instead of falling back to "everything off"
//   - a JSON snapshot that `flagkit lint --flags-file` reads in CI without any access to Flagsmith
import fs from 'node:fs';
import path from 'node:path';
import { adminOf, envOf } from './experiment.js';
import { loadFlags } from './flags.js';

const IDENT = /^[a-z0-9][a-z0-9_-]{0,99}$/i;
export const MARK = '/* flagkit:snapshot */';

export function snapshotOf(flags, envName, project) {
  return {
    project, environment: envName, generatedAt: new Date().toISOString(),
    flags: Object.fromEntries(flags.filter((f) => IDENT.test(f.name)).sort((a, b) => a.name.localeCompare(b.name)).map((f) => {
      const s = f.envs[envName];
      return [f.name, {
        type: f.type === 'MULTIVARIATE' ? 'multivariate' : 'standard',
        ...(f.type === 'MULTIVARIATE' ? { variants: ['control', ...f.variants.filter((v) => v !== 'control')] } : {}),
        description: f.description || undefined,
        default: s ? { enabled: s.enabled, value: s.value } : { enabled: false, value: null },
      }];
    })),
  };
}

export function render(snapshot, lang = 'ts') {
  const json = JSON.stringify(snapshot.flags, null, 2);
  const head = `// Generated by \`flagkit codegen\` from Flagsmith project "${snapshot.project}", environment "${snapshot.environment}".
// Do not edit by hand: re-run \`npm run flags:sync\` after changing flags in Flagsmith.
// FLAG_DEFAULTS are what the app uses when Flagsmith cannot be reached.
`;
  if (lang === 'js') {
    return `${head}
/** @typedef {${Object.keys(snapshot.flags).map((n) => JSON.stringify(n)).join(' | ') || 'never'}} FlagName */

export const FLAGS = ${MARK} ${json};

/** @type {Record<FlagName, { enabled: boolean, value: string | number | boolean | null }>} */
export const FLAG_DEFAULTS = Object.fromEntries(Object.entries(FLAGS).map(([k, v]) => [k, v.default]));

/** @param {string} name @returns {name is FlagName} */
export const isFlag = (name) => Object.prototype.hasOwnProperty.call(FLAGS, name);
`;
  }
  const variants = Object.entries(snapshot.flags).filter(([, f]) => f.variants)
    .map(([n, f]) => `  ${JSON.stringify(n)}: ${f.variants.map((v) => JSON.stringify(v)).join(' | ')};`).join('\n');
  return `${head}
export const FLAGS = ${MARK} ${json} as const;

export type FlagName = keyof typeof FLAGS;
export interface FlagVariants {
${variants}
}
export type MultivariateFlag = keyof FlagVariants;
export type FlagState = { enabled: boolean; value: string | number | boolean | null };

export const FLAG_DEFAULTS = Object.fromEntries(
  Object.entries(FLAGS).map(([k, v]) => [k, v.default]),
) as Record<FlagName, FlagState>;

export const isFlag = (name: string): name is FlagName => Object.prototype.hasOwnProperty.call(FLAGS, name);
`;
}

// Read the snapshot back out of a generated file (for lint in CI, with no Flagsmith access).
export function readSnapshot(file) {
  const text = fs.readFileSync(file, 'utf8');
  const i = text.indexOf(MARK);
  if (i < 0) throw new Error(`${file} was not generated by flagkit codegen`);
  const start = text.indexOf('{', i);
  let depth = 0, inStr = false, esc = false;
  for (let j = start; j < text.length; j++) {
    const c = text[j];
    if (inStr) { if (esc) esc = false; else if (c === '\\') esc = true; else if (c === '"') inStr = false; continue; }
    if (c === '"') inStr = true;
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) return JSON.parse(text.slice(start, j + 1));
  }
  throw new Error(`Could not read the flag snapshot in ${file}`);
}

export async function codegen(state, { env = 'Production', out, lang } = {}) {
  const e = envOf(state, env);
  const flags = await loadFlags(adminOf(state), { projectId: state.project.id, environments: state.environments });
  const file = out || (fs.existsSync('src') ? `src/flags.generated.${lang || (fs.existsSync('tsconfig.json') ? 'ts' : 'js')}` : `flags.generated.${lang || 'js'}`);
  const l = lang || (file.endsWith('.ts') ? 'ts' : 'js');
  fs.mkdirSync(path.dirname(path.resolve(file)), { recursive: true });
  const snap = snapshotOf(flags, e.name, state.project.name);
  fs.writeFileSync(file, render(snap, l));
  return { file, count: Object.keys(snap.flags).length, env: e.name };
}
